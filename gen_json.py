"""Write the machine-readable calendar files for the site: docs/data/<yyyy-yy>.json, timetable-<yyyy>.json, index.json."""
import json
import os

import railcal

FIRST_FY, LAST_FY = 1995, 2059
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "docs", "data")


def fy_label(fy):
    return f"{fy}/{(fy + 1) % 100:02d}"


def year_json(fy):
    label = fy_label(fy)
    cp, cpy = railcal.control_period(fy)
    poss = railcal.possession_periods(fy)
    return {
        "financial_year": label, "start": f"{fy}-04-01", "end": f"{fy + 1}-03-31",
        "control_period": cp, "control_period_year": cpy,
        "railway_periods": [
            {"year": label, "period": p, "label": f"{label} P{p:02d}", "start": s.isoformat(), "end": e.isoformat(),
             "days": (e - s).days + 1}
            for p, s, e in railcal.railway_periods(fy)],
        "possession_year": {
            "year": label, "start": railcal.possession_year_start(fy).isoformat(),
            "end": (railcal.possession_year_start(fy + 1) - railcal.DAY).isoformat(),
            "weeks": railcal.possession_year_weeks(fy),
            "periods": [
                {"year": label, "period": p, "label": f"{label} P{p:02d}", "start": s.isoformat(), "end": e.isoformat(),
                 "first_week": fw, "last_week": lw, "weeks": lw - fw + 1}
                for p, s, e, fw, lw in poss],
            "weeks_list": [
                {"year": label, "week": w, "period": p, "week_in_period": wip, "start": s.isoformat(),
                 "end": e.isoformat(), "label": f"{label} W{w:02d} (P{p:02d} wk {wip})"}
                for w, p, wip, s, e in railcal.possession_weeks(fy)],
        },
    }


def iso_range(start, end, weeks):
    return {"start": start.isoformat(), "end": end.isoformat(), "weeks": weeks}


def timetable_json(y):
    t = railcal.timetable(y)
    return {
        "timetable_year": y, "label": f"TT{y}",
        "start": t["principal"][0].isoformat(), "end": t["subsidiary"][1].isoformat(), "weeks": t["weeks"],
        "principal": iso_range(*t["principal"]), "subsidiary": iso_range(*t["subsidiary"]),
        "blocks": [{"block": n, **iso_range(s, e, w)} for n, s, e, w in t["blocks"]],
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    files = []
    for fy in range(FIRST_FY, LAST_FY + 1):
        name = f"{fy}-{(fy + 1) % 100:02d}.json"
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            json.dump(year_json(fy), f, indent=1)
        files.append({"financial_year": fy_label(fy), "file": name})
    tt_files = []
    for y in range(FIRST_FY + 1, LAST_FY + 2):
        name = f"timetable-{y}.json"
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            json.dump(timetable_json(y), f, indent=1)
        tt_files.append({"timetable_year": y, "file": name})
    index = {
        "description": "GB railway calendar: railway periods (Sun-Sat, 1 Apr - 31 Mar), possession weeks (Sat-Fri) "
                       "and timetable years with period blocks. Generated by gen_json.py from railcal.py.",
        "dates": "ISO 8601 calendar dates; every range is inclusive of start and end.",
        "financial_years": files, "timetable_years": tt_files,
    }
    with open(os.path.join(OUT, "index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, indent=1)
    print(f"wrote {len(files)} financial years and {len(tt_files)} timetable years to {OUT}")


if __name__ == "__main__":
    main()
